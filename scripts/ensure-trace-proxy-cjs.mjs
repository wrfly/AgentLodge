/**
 * trace-proxy/ is CommonJS (`require(...)`), while the repository root's package.json says
 * `"type": "module"`. Node decides a file's module type from the *nearest* package.json, so
 * with none in trace-proxy/ it walks up to the root one, loads proxy.js as ESM, and dies on
 * the first require:
 *
 *   ReferenceError: require is not defined in ES module scope
 *
 * So trace-proxy/ needs a package.json declaring `"type": "commonjs"`. It used to be synced in
 * from elsewhere and replaced wholesale — four times — so a file maintained by hand inside it
 * never survived, and the marker ended up gitignored and generated instead. The code is
 * maintained here now, which makes committing the marker the simpler arrangement; until
 * somebody makes that change, this keeps it in place.
 *
 *
 * This runs before every `npm run trace` and puts the file back when it is missing. What it
 * writes is a bare marker — no scripts, no dependencies. The integration lives in the root's
 * scripts/, and trace-proxy/ stays clean and replaceable.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const marker = path.join(root, 'trace-proxy', 'package.json');

if (!fs.existsSync(path.join(root, 'trace-proxy', 'proxy.js'))) {
  console.error('✗ trace-proxy/proxy.js is missing — is the trace proxy installed?');
  process.exit(1);
}

let need = true;
try {
  need = JSON.parse(fs.readFileSync(marker, 'utf8')).type !== 'commonjs';
} catch {
  /* Missing, or not valid JSON — either way it needs rewriting */
}

if (need) {
  fs.writeFileSync(
    marker,
    `${JSON.stringify(
      {
        name: '@agentlodge/trace-proxy-marker',
        private: true,
        type: 'commonjs',
        _comment:
          'Generated by scripts/ensure-trace-proxy-cjs.mjs. trace-proxy/ is CommonJS while the ' +
          'repository root is ESM; without this marker Node loads it as ESM and reports ' +
          '"require is not defined". Rebuilt automatically after trace-proxy/ is replaced, so ' +
          'there is nothing to maintain by hand.',
      },
      null,
      2,
    )}\n`,
  );
  console.log('· wrote trace-proxy/package.json (the CommonJS marker)');
}
